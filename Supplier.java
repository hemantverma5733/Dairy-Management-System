package com.smartdairy.entity;

public class Supplier {
    private int id; private String name, mobile, address, animalType, bankDetails, status;
    public int getId(){return id;} public void setId(int v){id=v;}
    public String getName(){return name;} public void setName(String v){name=v;}
    public String getMobile(){return mobile;} public void setMobile(String v){mobile=v;}
    public String getAddress(){return address;} public void setAddress(String v){address=v;}
    public String getAnimalType(){return animalType;} public void setAnimalType(String v){animalType=v;}
    public String getBankDetails(){return bankDetails;} public void setBankDetails(String v){bankDetails=v;}
    public String getStatus(){return status;} public void setStatus(String v){status=v;}
}
